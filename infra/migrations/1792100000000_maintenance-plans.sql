CREATE TABLE maintenance_plan (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  make_id UUID NOT NULL REFERENCES vehicle_make (id),
  model_id UUID,
  generation_id UUID,
  engine_id UUID REFERENCES vehicle_engine (id),
  name TEXT NOT NULL,
  source TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft',
  -- Set while AI makes the draft (requirement 3: one at a time per area);
  -- cleared when the draft is written, the row removed when AI fails.
  generating_since TIMESTAMPTZ,
  ai_job_id UUID REFERENCES ai_job (id) ON DELETE SET NULL,
  copied_from_id UUID REFERENCES maintenance_plan (id),
  created_by_admin_id UUID REFERENCES admin_user (id),
  confirmed_by_admin_id UUID REFERENCES admin_user (id),
  confirmed_at TIMESTAMPTZ,
  archived_at TIMESTAMPTZ,
  version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT maintenance_plan_model_fkey FOREIGN KEY (model_id, make_id)
    REFERENCES vehicle_model (id, make_id),
  CONSTRAINT maintenance_plan_generation_fkey FOREIGN KEY (generation_id, model_id)
    REFERENCES vehicle_generation (id, model_id),
  CONSTRAINT maintenance_plan_generation_model_check CHECK (
    generation_id IS NULL OR model_id IS NOT NULL
  ),
  CONSTRAINT maintenance_plan_name_check CHECK (
    btrim(name) <> '' AND char_length(name) <= 120
  ),
  CONSTRAINT maintenance_plan_source_check CHECK (source IN ('ai_draft', 'manual', 'official')),
  CONSTRAINT maintenance_plan_status_check CHECK (status IN ('draft', 'active', 'archived')),
  CONSTRAINT maintenance_plan_archived_at_check CHECK (
    (status = 'archived') = (archived_at IS NOT NULL)
  ),
  -- Only a draft is ever being generated.
  CONSTRAINT maintenance_plan_generating_check CHECK (
    generating_since IS NULL OR (status = 'draft' AND source = 'ai_draft')
  ),
  CONSTRAINT maintenance_plan_confirmed_check CHECK (
    status <> 'active' OR confirmed_at IS NOT NULL
  ),
  CONSTRAINT maintenance_plan_version_check CHECK (version > 0)
);

-- One active plan per area (NULL is «any» and equal to NULL).
CREATE UNIQUE INDEX maintenance_plan_active_scope_key ON maintenance_plan
  (make_id, model_id, generation_id, engine_id) NULLS NOT DISTINCT
  WHERE status = 'active';
-- One draft being generated by AI per area.
CREATE UNIQUE INDEX maintenance_plan_generating_scope_key ON maintenance_plan
  (make_id, model_id, generation_id, engine_id) NULLS NOT DISTINCT
  WHERE generating_since IS NOT NULL;
-- The plans of a car are read by its make (then the finer levels decide).
CREATE INDEX maintenance_plan_make_idx ON maintenance_plan (make_id, status);
CREATE INDEX maintenance_plan_model_idx ON maintenance_plan (model_id) WHERE model_id IS NOT NULL;

CREATE TABLE maintenance_plan_item (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plan_id UUID NOT NULL REFERENCES maintenance_plan (id),
  position INTEGER NOT NULL DEFAULT 0,
  kind TEXT NOT NULL,
  interval_km INTEGER,
  interval_months SMALLINT,
  first_km INTEGER,
  first_months SMALLINT,
  service_codes TEXT[] NOT NULL DEFAULT '{}',
  -- The rule: `category` — a subcategory (of goods for a part, of services
  -- for a service) and conditions on its characteristics; `items` —
  -- particular items; NULL — none yet (an element AI could not map).
  target_kind TEXT,
  target_category_id UUID,
  target_category_kind TEXT,
  target_category_level SMALLINT NOT NULL DEFAULT 2,
  target_attributes JSONB NOT NULL DEFAULT '[]'::jsonb,
  target_item_ids UUID[] NOT NULL DEFAULT '{}',
  quantity SMALLINT,
  note TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  confirmed_by_admin_id UUID REFERENCES admin_user (id),
  confirmed_at TIMESTAMPTZ,
  archived_at TIMESTAMPTZ,
  version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT maintenance_plan_item_kind_check CHECK (kind IN ('part', 'service')),
  CONSTRAINT maintenance_plan_item_category_fkey
    FOREIGN KEY (target_category_id, target_category_kind, target_category_level)
    REFERENCES category (id, kind, level),
  CONSTRAINT maintenance_plan_item_category_level_check CHECK (target_category_level = 2),
  -- A part is picked from goods, a service from services.
  CONSTRAINT maintenance_plan_item_category_kind_check CHECK (
    target_category_kind IS NULL
    OR (kind = 'part' AND target_category_kind = 'goods')
    OR (kind = 'service' AND target_category_kind = 'services')
  ),
  CONSTRAINT maintenance_plan_item_target_check CHECK (
    (target_kind IS NULL AND status IN ('proposed', 'archived')
      AND target_category_id IS NULL AND cardinality(target_item_ids) = 0
      AND target_attributes = '[]'::jsonb)
    OR (target_kind = 'category' AND target_category_id IS NOT NULL
      AND target_category_kind IS NOT NULL AND cardinality(target_item_ids) = 0
      AND jsonb_typeof(target_attributes) = 'array')
    OR (target_kind = 'items' AND target_category_id IS NULL
      AND cardinality(target_item_ids) BETWEEN 1 AND 20
      AND target_attributes = '[]'::jsonb)
  ),
  CONSTRAINT maintenance_plan_item_interval_check CHECK (
    (interval_km IS NOT NULL OR interval_months IS NOT NULL)
    AND (interval_km IS NULL OR interval_km BETWEEN 1000 AND 120000)
    AND (interval_months IS NULL OR interval_months BETWEEN 1 AND 120)
    AND (first_km IS NULL OR (interval_km IS NOT NULL AND first_km BETWEEN 1 AND interval_km - 1))
    AND (first_months IS NULL
      OR (interval_months IS NOT NULL AND first_months BETWEEN 1 AND interval_months - 1))
  ),
  CONSTRAINT maintenance_plan_item_codes_check CHECK (cardinality(service_codes) <= 12),
  CONSTRAINT maintenance_plan_item_quantity_check CHECK (quantity IS NULL OR quantity BETWEEN 1 AND 100),
  CONSTRAINT maintenance_plan_item_note_check CHECK (note IS NULL OR char_length(note) <= 200),
  CONSTRAINT maintenance_plan_item_status_check CHECK (status IN ('proposed', 'active', 'archived')),
  CONSTRAINT maintenance_plan_item_archived_at_check CHECK (
    (status = 'archived') = (archived_at IS NOT NULL)
  ),
  CONSTRAINT maintenance_plan_item_version_check CHECK (version > 0)
);

CREATE INDEX maintenance_plan_item_plan_idx ON maintenance_plan_item (plan_id, position);
CREATE INDEX maintenance_plan_item_category_idx ON maintenance_plan_item (target_category_id)
  WHERE target_category_id IS NOT NULL;

