-- A plan is scoped by the vehicle catalog: a make (required) and,
-- optionally, a model, a generation and an engine — the levels agree, as a
-- compatibility record's do. `source`: `ai_draft` — a draft AI made from
-- open data, `manual` — written by an administrator, `official` — the
-- maker's data (none yet: it comes the same way, with its source).
-- `status`: `draft` → `active` (an administrator confirmed it) →
-- `archived`; plans are never deleted. One active plan per area; drafts —
-- any number, but only one of them is being generated by AI at a time.
--
-- An element is a piece of work by an interval (km and/or months, «каждые
-- N», the first time optionally earlier) with the rule that picks what the
-- platform sells for it: a subcategory of the catalog with conditions on
-- its characteristics (the very filters of the client list, `attributes`),
-- or particular items. An element AI proposed is `proposed` until an
-- administrator confirms it; one whose subcategory AI named but the
-- catalog has not («unmapped») has no rule at all and can't be confirmed
-- until it gets one. Its short title is a text of `translation`
-- (`maintenance_plan_item`, `name`), translated automatically like the
-- names of the catalog.

